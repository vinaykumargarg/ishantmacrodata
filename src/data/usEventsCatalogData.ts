export function getEventById(id: string): UsCatalogEvent | undefined {
  return US_EVENT_CATALOG.find((e) => e.id === id);
}

export function getEventsByCategory(category: string): UsCatalogEvent[] {
  if (category === 'All Categories') return US_EVENT_CATALOG;
  return US_EVENT_CATALOG.filter((e) => e.category === category);
}

export function searchEvents(query: string): UsCatalogEvent[] {
  const q = query.toLowerCase().trim();
  if (!q) return US_EVENT_CATALOG;
  return US_EVENT_CATALOG.filter(
    (e) =>
      e.id.toLowerCase().includes(q) ||
      e.event.toLowerCase().includes(q) ||
      e.category.toLowerCase().includes(q) ||
      e.agency.toLowerCase().includes(q) ||
      e.measure.toLowerCase().includes(q) ||
      e.note.toLowerCase().includes(q)
  );
}
